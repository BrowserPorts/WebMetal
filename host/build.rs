//! With the `native` feature, binds the webgpu.h C API of a native WebGPU implementation.
//!
//! The implementation is chosen at build time:
//!
//! - `WEBGPU_NATIVE`: `dawn` or `wgpu-native`.
//! - `WEBGPU_NATIVE_DIR`: its install root, holding `include/webgpu/webgpu.h` and `lib/`. Dawn is linked statically
//!   (`lib/libwebgpu_dawn.a`, the layout of Dawn's release archives and of `cmake --install`); wgpu-native
//!   dynamically (`lib/libwgpu_native.dylib` or `.so`, the layout of its release archives), with the directory added to
//!   the run-time search path.
//!
//! The Rust declarations are generated by bindgen from that implementation's own header, so every structure layout,
//! enumerator and function signature is the one the linked library was built with. The build fails when the feature is
//! on and either variable is missing.
//!
//! Every build reads two files of device data the user supplies; the repository holds none, and the build fails when
//! either variable is missing:
//!
//! - `WEBMETAL_PROFILE`: the A10X device profile, described in `src/format/profile.rs`;
//! - `WEBMETAL_AGX_TEXTURE_FORMATS`: the A10X driver's texture format table, described in `src/mem/agx/mod.rs`.

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    profile::generate();
    agx_texture_formats();
    #[cfg(feature = "native")]
    native::bind();
    println!("cargo:rustc-check-cfg=cfg(webgpu_native, values(\"dawn\", \"wgpu-native\"))");
}

/// The A10X driver's texture format table, as Rust items (`src/mem/agx/mod.rs` lists them), copied to
/// `$OUT_DIR/agx_texture_formats.rs` for `mem::agx::formats`. Inner doc comments become plain comments there, since the
/// file is included into a module rather than being one.
fn agx_texture_formats() {
    use std::env;
    use std::fs;
    use std::path::PathBuf;

    println!("cargo:rerun-if-env-changed=WEBMETAL_AGX_TEXTURE_FORMATS");
    let path = match env::var("WEBMETAL_AGX_TEXTURE_FORMATS") {
        Ok(v) if !v.is_empty() => v,
        _ => panic!(
            "WEBMETAL_AGX_TEXTURE_FORMATS is not set: the build needs the A10X driver's texture format table, a Rust \
             file the user supplies (its items are described in host/src/mem/agx/mod.rs). Set \
             WEBMETAL_AGX_TEXTURE_FORMATS to its path."
        ),
    };
    let file = fs::canonicalize(&path).unwrap_or_else(|e| {
        panic!("the texture format table {path} (WEBMETAL_AGX_TEXTURE_FORMATS) cannot be opened: {e}")
    });
    println!("cargo:rerun-if-changed={}", file.display());
    let text = fs::read_to_string(&file).unwrap_or_else(|e| {
        panic!("the texture format table {path} (WEBMETAL_AGX_TEXTURE_FORMATS) cannot be read: {e}")
    });
    let mut out = String::new();
    for line in text.lines() {
        match line.strip_prefix("//!") {
            Some(rest) => out.push_str(&format!("//{rest}\n")),
            None => out.push_str(&format!("{line}\n")),
        }
    }
    let dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(dir.join("agx_texture_formats.rs"), out).unwrap();
}

/// The A10X device profile: the records the format module reads, written to `$OUT_DIR/a10x_profile.rs`.
mod profile {
    use std::env;
    use std::fmt::Write;
    use std::fs;
    use std::path::PathBuf;

    /// The capability getters the format module reads, by their MTLDevice / MTLDeviceSPI selector, with the field of
    /// `A10xGetters` (src/format/profile.rs) each one fills.
    const GETTERS: [(&str, &str); 20] = [
        ("isASTCPixelFormatsSupported", "is_astc_pixel_formats_supported"),
        ("supportsASTCTextureCompression", "supports_astc_texture_compression"),
        ("supportsASTCHDRTextureCompression", "supports_astc_hdr_texture_compression"),
        ("supports3DASTCTextures", "supports_3d_astc_textures"),
        ("supportsBCTextureCompression", "supports_bc_texture_compression"),
        ("isBCTextureCompressionSupported", "is_bc_texture_compression_supported"),
        ("supports3DBCTextures", "supports_3d_bc_textures"),
        ("supportsCompressedTextureViewSPI", "supports_compressed_texture_view_spi"),
        ("isFloat32FilteringSupported", "is_float32_filtering_supported"),
        ("isRGB10A2GammaSupported", "is_rgb10a2_gamma_supported"),
        ("supportsExtendedXR10Formats", "supports_extended_xr10_formats"),
        ("supportsPublicXR10Formats", "supports_public_xr10_formats"),
        ("supportsExtendedYUVFormats", "supports_extended_yuv_formats"),
        ("supportsYCBCRFormats", "supports_ycbcr_formats"),
        ("supportsYCBCRFormats12", "supports_ycbcr_formats_12"),
        ("supportsYCBCRFormatsPQ", "supports_ycbcr_formats_pq"),
        ("supportsYCBCRFormatsXR", "supports_ycbcr_formats_xr"),
        ("supportsYCBCRPackedFormats12", "supports_ycbcr_packed_formats_12"),
        ("supportsYCBCRPackedFormatsPQ", "supports_ycbcr_packed_formats_pq"),
        ("supportsYCBCRPackedFormatsXR", "supports_ycbcr_packed_formats_xr"),
    ];

    /// The named flags of `word_08` and the bit each decodes.
    const FLAGS: [(&str, u32); 9] = [
        ("supported", 0),
        ("compressed", 10),
        ("compatible_float", 16),
        ("compatible_half", 17),
        ("compatible_int", 18),
        ("compatible_uint", 19),
        ("compatible_short", 20),
        ("compatible_ushort", 21),
        ("compatible_ulong", 29),
    ];

    fn fail(path: &str, what: String) -> ! {
        panic!("the device profile {path} (WEBMETAL_PROFILE) is not usable: {what}")
    }

    fn integer(path: &str, at: &str, v: Option<&toml::Value>) -> i64 {
        match v {
            Some(toml::Value::Integer(i)) => *i,
            Some(other) => fail(path, format!("{at} is a {}, not an integer", other.type_str())),
            None => fail(path, format!("{at} is missing")),
        }
    }

    fn boolean(path: &str, at: &str, v: Option<&toml::Value>) -> bool {
        match v {
            Some(toml::Value::Boolean(b)) => *b,
            Some(other) => fail(path, format!("{at} is a {}, not a boolean", other.type_str())),
            None => fail(path, format!("{at} is missing")),
        }
    }

    fn table<'a>(path: &str, at: &str, v: Option<&'a toml::Value>) -> &'a toml::Table {
        match v {
            Some(toml::Value::Table(t)) => t,
            Some(_) => fail(path, format!("{at} is not a table")),
            None => fail(path, format!("[{at}] is missing")),
        }
    }

    fn values(path: &str, at: &str, v: Option<&toml::Value>) -> Vec<u32> {
        let Some(toml::Value::Array(a)) = v else { fail(path, format!("{at} is missing or not an array")) };
        a.iter()
            .map(|x| {
                let v = integer(path, at, Some(x));
                u32::try_from(v).unwrap_or_else(|_| fail(path, format!("{at} holds {v}, not a pixel format value")))
            })
            .collect()
    }

    pub fn generate() {
        println!("cargo:rerun-if-env-changed=WEBMETAL_PROFILE");
        let path = match env::var("WEBMETAL_PROFILE") {
            Ok(v) if !v.is_empty() => v,
            _ => panic!(
                "WEBMETAL_PROFILE is not set: the build needs the A10X device profile, a TOML file the user supplies \
                 (its fields are described in host/src/format/profile.rs). Set WEBMETAL_PROFILE to its path."
            ),
        };
        let file = fs::canonicalize(&path).unwrap_or_else(|e| fail(&path, format!("cannot open it: {e}")));
        println!("cargo:rerun-if-changed={}", file.display());
        let text = fs::read_to_string(&file).unwrap_or_else(|e| fail(&path, format!("cannot read it: {e}")));
        let profile: toml::Table = text.parse().unwrap_or_else(|e| fail(&path, format!("not TOML: {e}")));

        let list = table(&path, "pixel_format_list", profile.get("pixel_format_list"));
        let known = values(&path, "pixel_format_list.known", list.get("known"));
        let private = values(&path, "pixel_format_list.private", list.get("private"));
        if known.is_empty() || !known.windows(2).all(|w| w[0] < w[1]) {
            fail(&path, "pixel_format_list.known is not a strictly increasing list of formats".into());
        }
        if let Some(p) = private.iter().find(|p| !known.contains(p)) {
            fail(&path, format!("pixel_format_list.private lists {p}, which pixel_format_list.known does not"));
        }
        let records = table(&path, "pixel_formats", profile.get("pixel_formats"));

        let mut out = String::new();
        writeln!(out, "pub static A10X_FORMATS: [A10xFormatRecord; {}] = [", known.len()).unwrap();
        for v in &known {
            let at = format!("pixel_formats.{v}");
            let r = table(&path, &at, records.get(&v.to_string()));
            let word = integer(&path, &format!("{at}.word_08"), r.get("word_08"));
            let word =
                u32::try_from(word).unwrap_or_else(|_| fail(&path, format!("{at}.word_08 is not a 32-bit word")));
            for (name, bit) in FLAGS {
                if boolean(&path, &format!("{at}.{name}"), r.get(name)) != (word >> bit & 1 != 0) {
                    fail(&path, format!("{at}.{name} disagrees with bit {bit} of word_08"));
                }
            }
            writeln!(
                out,
                "    A10xFormatRecord {{ value: {v}, word_08: {word:#010x}, supported: {}, compressed: {}, private: {} }},",
                word & 1 != 0,
                word >> 10 & 1 != 0,
                private.contains(v)
            )
            .unwrap();
        }
        out.push_str("];\n\npub static A10X_GETTERS: A10xGetters = A10xGetters {\n");
        for (selector, field) in GETTERS {
            // Protocol getters are in [getters], driver-class methods outside the protocols in [driver_getters].
            let section = ["getters", "driver_getters"]
                .into_iter()
                .find(|s| table(&path, s, profile.get(*s)).contains_key(selector))
                .unwrap_or_else(|| fail(&path, format!("neither [getters] nor [driver_getters] has {selector}")));
            let value = boolean(&path, &format!("{section}.{selector}"), profile[section].get(selector));
            writeln!(out, "    {field}: {value},").unwrap();
        }
        out.push_str("};\n");
        let dir = PathBuf::from(env::var("OUT_DIR").unwrap());
        fs::write(dir.join("a10x_profile.rs"), out).unwrap();
        // The tests compare the executor's constants with the profile's other sections.
        println!("cargo:rustc-env=WEBMETAL_PROFILE_FILE={}", file.display());
    }
}

#[cfg(feature = "native")]
mod native {
    use std::env;
    use std::fs;
    use std::path::{Path, PathBuf};
    use std::process::Command;

    /// The wgpu-native release whose unimplemented entry points (src/unimplemented.rs) the binding was written against.
    const WGPU_NATIVE_CHECKED: &str = "v29.0.1.1";

    fn var(name: &str) -> String {
        println!("cargo:rerun-if-env-changed={name}");
        match env::var(name) {
            Ok(v) if !v.is_empty() => v,
            _ => panic!(
                "the `native` feature needs {name}: set WEBGPU_NATIVE to `dawn` or `wgpu-native` and WEBGPU_NATIVE_DIR to \
                 the implementation's install root (with include/webgpu/webgpu.h and lib/)"
            ),
        }
    }

    pub fn bind() {
        let which = var("WEBGPU_NATIVE");
        let root = PathBuf::from(var("WEBGPU_NATIVE_DIR"));
        let include = root.join("include");
        let lib = root.join("lib");
        let header = include.join("webgpu").join("webgpu.h");
        if !header.is_file() {
            panic!("{} does not exist", header.display());
        }
        let mut wrapper = String::from("#include <webgpu/webgpu.h>\n");

        let version = match which.as_str() {
            "dawn" => {
                let archive = lib.join("libwebgpu_dawn.a");
                if !archive.is_file() {
                    panic!("{} does not exist", archive.display());
                }
                println!("cargo:rerun-if-changed={}", archive.display());
                println!("cargo:rustc-link-search=native={}", lib.display());
                println!("cargo:rustc-link-lib=static=webgpu_dawn");
                if cfg!(target_os = "macos") || env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
                    println!("cargo:rustc-link-lib=c++");
                    // The frameworks Dawn's exported CMake target links (lib/cmake/Dawn/DawnTargets.cmake).
                    for fw in ["CoreFoundation", "Foundation", "IOSurface", "QuartzCore", "Cocoa", "IOKit", "Metal"] {
                        println!("cargo:rustc-link-lib=framework={fw}");
                    }
                } else {
                    println!("cargo:rustc-link-lib=stdc++");
                }
                dawn_version(&include, &root)
            }
            "wgpu-native" => {
                wrapper.push_str("#include <webgpu/wgpu.h>\n");
                let dylib =
                    ["libwgpu_native.dylib", "libwgpu_native.so"].iter().map(|n| lib.join(n)).find(|p| p.is_file());
                let Some(dylib) = dylib else { panic!("no libwgpu_native.dylib or .so in {}", lib.display()) };
                println!("cargo:rerun-if-changed={}", dylib.display());
                println!("cargo:rustc-link-search=native={}", lib.display());
                println!("cargo:rustc-link-lib=dylib=wgpu_native");
                println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
                let tag = root.join("wgpu-native-meta").join("wgpu-native-git-tag");
                let tag = fs::read_to_string(&tag).map(|t| t.trim().to_string()).unwrap_or_default();
                if tag != WGPU_NATIVE_CHECKED {
                    println!(
                        "cargo:warning=linking wgpu-native {tag:?}; the binding's list of entry points wgpu-native does not \
                         implement was read from {WGPU_NATIVE_CHECKED} and must be checked against this release"
                    );
                }
                format!("wgpu-native {tag}")
            }
            other => panic!("WEBGPU_NATIVE must be `dawn` or `wgpu-native`, not `{other}`"),
        };
        println!("cargo:rustc-cfg=webgpu_native=\"{which}\"");
        println!("cargo:rerun-if-changed={}", header.display());

        let out = PathBuf::from(env::var("OUT_DIR").unwrap());
        let mut builder = bindgen::Builder::default()
            .header_contents("webmetal_webgpu.h", &wrapper)
            .clang_arg(format!("-I{}", include.display()))
            .allowlist_function("wgpu.*")
            .allowlist_type("WGPU.*")
            .allowlist_var("WGPU.*")
            .prepend_enum_name(false)
            .default_enum_style(bindgen::EnumVariation::Consts)
            .layout_tests(true)
            .derive_default(false)
            .generate_comments(false);
        if let Some(sdk) = macos_sdk() {
            builder = builder.clang_arg(format!("-isysroot{sdk}"));
        }
        let bindings = builder.generate().expect("bindgen could not process webgpu.h");
        bindings.write_to_file(out.join("webgpu_sys.rs")).expect("write webgpu_sys.rs");
        let text = fs::read_to_string(out.join("webgpu_sys.rs")).unwrap();

        // Every enumerator of every enum of the header, so the binding can map IDL enum values to them by name.
        let mut meta = String::new();
        meta.push_str(&format!(
            "/// The implementation and version this build links.\npub const IMPLEMENTATION: &str = {version:?};\n"
        ));
        meta.push_str(&format!(
            "/// The header bindgen read.\npub const HEADER: &str = {:?};\n",
            header.display().to_string()
        ));
        meta.push_str("/// Every enumerator of the header: (enum type, enumerator name after the `_`, value).\n");
        meta.push_str("pub const C_ENUMS: &[(&str, &str, u32)] = &[\n");
        let mut n = 0;
        for line in text.lines() {
            let l = line.trim();
            let Some(rest) = l.strip_prefix("pub const WGPU") else { continue };
            let Some((name, rest)) = rest.split_once(": WGPU") else { continue };
            let Some((ty, value)) = rest.split_once(" = ") else { continue };
            let value = value.trim_end_matches(';');
            let Some((ename, suffix)) = name.split_once('_') else { continue };
            if ename != ty {
                continue;
            }
            let v: u64 = if let Some(h) = value.strip_prefix("0x") {
                u64::from_str_radix(h, 16).unwrap()
            } else {
                match value.parse() {
                    Ok(v) => v,
                    Err(_) => continue,
                }
            };
            if v > u64::from(u32::MAX) {
                continue;
            }
            meta.push_str(&format!("    (\"WGPU{ty}\", {suffix:?}, {v}),\n"));
            n += 1;
        }
        meta.push_str("];\n");
        assert!(n > 100, "found only {n} enumerators in the bindgen output");
        fs::write(out.join("webgpu_meta.rs"), meta).unwrap();
    }

    fn dawn_version(include: &Path, root: &Path) -> String {
        let name = root.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        let header = include.join("dawn").join("dawn_version.h");
        let minor = fs::read_to_string(&header).ok().and_then(|t| {
            t.lines().find_map(|l| l.strip_prefix("#define DAWN_MINOR_VERSION ").map(|v| v.trim().to_string()))
        });
        match minor {
            Some(m) => format!("Dawn {name} (DAWN_MINOR_VERSION {m})"),
            None => format!("Dawn {name}"),
        }
    }

    fn macos_sdk() -> Option<String> {
        if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
            return None;
        }
        println!("cargo:rerun-if-env-changed=SDKROOT");
        if let Ok(s) = env::var("SDKROOT") {
            return Some(s);
        }
        let out = Command::new("xcrun").args(["--sdk", "macosx", "--show-sdk-path"]).output().ok()?;
        out.status.success().then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
    }
}
